fun main() {
    var num1 = 10
    var num2 = 9

    println(" The sum of the numbers $num1 and $num2 is ${num1 + num2}")
    println(" The division of numbers $num1 / $num2 is ${num1 / num2}")
    println(" The rest of the division of numbers $num1 / $num2 is ${num1 % num2}")
    println(" The pre-increment of number $num1 ${++num1}")
    println(" The post-increment of number $num1 ${num1++}")
    println(" The pre-decrement of number $num1 ${--num1}")
    println(" The post-decrement of number $num1 ${num1--}")




}